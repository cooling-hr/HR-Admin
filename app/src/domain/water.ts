// 4 قناني/يوم من أيار حتى أيلول، وقنينتان من تشرين الأول حتى نيسان
export const getWaterSeasonalRate = (monthStr: string): number => {
    const m = parseInt(monthStr.split('-')[1], 10);
    return (m >= 5 && m <= 9) ? 4 : 2;
};

